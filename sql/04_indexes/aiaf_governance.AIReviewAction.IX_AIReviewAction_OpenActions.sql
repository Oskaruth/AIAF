CREATE NONCLUSTERED INDEX [IX_AIReviewAction_OpenActions] ON [aiaf_governance].[AIReviewAction]
(
	[DueAt] ASC
)
INCLUDE([AssignedOwner],[ActionStatus],[ReviewItemId])
WHERE ([ActionStatus] IN ('OPEN', 'IN_PROGRESS'))
WITH (PAD_INDEX = OFF, STATISTICS_NORECOMPUTE = OFF, SORT_IN_TEMPDB = OFF, DROP_EXISTING = OFF, ONLINE = OFF, ALLOW_ROW_LOCKS = ON, ALLOW_PAGE_LOCKS = ON, OPTIMIZE_FOR_SEQUENTIAL_KEY = OFF) ON [PRIMARY]
GO
